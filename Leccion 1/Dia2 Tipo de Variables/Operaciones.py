x=6
y=2
z=7

print(f"{x} mas {y} es igual a {x+y}")
print(f"{x} menos {y} es igual a {x-y}")
print(f"{x} por {y} es igual a {x*y}")
print(f"{x} dividido {y} es igual a {x/y}")

#redondeo abajo sin decimales
print(f"{z} dividido hacia abajo de  {y} es igual a {z//y}")

#resto
print(f"{z} da de resto de  {y} es igual a {z%y}")

#elevado al cuadrado o al cubo
print(f"{x} elevado al cuadrado {y} es igual a {x**y}")
print(f"{x} elevado al cubo {y} es igual a {x**3}")

# raíz cuadrada
print(f"La raíz cuadrada de {x} es {x**0.5}")
